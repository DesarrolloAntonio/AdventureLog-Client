@OptIn(ExperimentalMaterial3ExpressiveApi::class)
@Composable
fun AppTheme(
    content: @Composable () -> Unit
) {
    val settingsRepository: SettingsRepository = koinInject()
    val themeMode by settingsRepository.getThemeMode().collectAsState()
    val useDynamicColors by settingsRepository.getUseDynamicColors().collectAsState()
    
    // Determine if dark mode should be used based on the theme mode
    val isDarkTheme = when (themeMode) {
        ThemeMode.DARK -> true
        ThemeMode.LIGHT -> false
        ThemeMode.AUTO -> isSystemInDarkTheme()
    }
    
    // Determine the color scheme to use
    val colorScheme = when {
        useDynamicColors && isDynamicColorSupported -> {
            getDynamicColorScheme(isDarkTheme) ?: if (isDarkTheme) darkScheme else lightScheme
        }
        isDarkTheme -> darkScheme
        else -> lightScheme
    }

    // Expressive, not plain Material: it installs the spring-based motion scheme components read
    // for their own animations, and marks the composition so components take expressive defaults.
    MaterialExpressiveTheme(
        colorScheme = colorScheme,
        motionScheme = MotionScheme.expressive(),
        shapes = AdventureShapes,
        typography = getAppTypography(),
        content = content
    )
}